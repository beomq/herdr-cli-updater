function plannedOfficial(directory:string,catalogId:'codex'|'amp'):OfficialInstallPlan {
  return {catalogId,method:'npm',sourceUrl:'https://example.test/official',target:join(directory,'global'),
    executable:join(directory,'global/bin',catalogId),manager:process.execPath,args:[],env:{},recipeHash:'a'.repeat(64)};
}
function publishOfficial(plan:OfficialInstallPlan):void {
  const name=catalogPackage(plan.catalogId);if(!name)throw new Error('missing package');
  const root=join(plan.target,'lib/node_modules',name);
  mkdirSync(root,{recursive:true});mkdirSync(join(plan.executable,'..'),{recursive:true});
  writeFileSync(join(root,'package.json'),JSON.stringify({name,version:'1.2.3',bin:{[plan.catalogId]:'cli.js'}}));
  writeFileSync(join(root,'cli.js'),'#!/bin/sh\necho 1.2.3\n',{mode:0o755});
  symlinkSync(join(root,'cli.js'),plan.executable);
}

async function fixture(fails=false,platform:NodeJS.Platform=process.platform,arch:string=process.arch){
  const directory=realpathSync(mkdtempSync('/tmp/cli-catalog-'));
  symlinkSync(process.execPath,join(directory,'npm'));
  const store=new AppStore(directory);let calls=0;
  const entered=Promise.withResolvers<void>(),release=Promise.withResolvers<void>();
  const options={directory,home:directory,path:directory,prefixes:[join(directory,'global')],store,changed:()=>{}};
  const planOfficial:NonNullable<Parameters<typeof createCatalog>[1]>['planOfficial']=async input=>{
    if(input.catalogId!=='codex'&&input.catalogId!=='amp')throw new Error('unexpected plan');
    return plannedOfficial(directory,input.catalogId);
  };
  const catalog=createCatalog(options,{
    platform,arch,
    planOfficial,
    executeOfficial:async plan=>{calls++;entered.resolve();await release.promise;if(fails)throw new Error('fixture failed');publishOfficial(plan);return '1.2.3';},
    verify:async()=> '1.2.3',
  });
  await catalog.settled();
  return {directory,catalog,store,options,planOfficial,entered,release,calls:()=>calls,close:async()=>{await catalog.settled();store.close();rmSync(directory,{recursive:true,force:true});}};
}
