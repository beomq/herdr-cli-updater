function record(value: unknown): value is Record<string, unknown> {
  return typeof value === "object" && value !== null && !Array.isArray(value);
}
function exact(value: Record<string, unknown>, keys: readonly string[]): boolean {
  return Object.keys(value).length === keys.length && keys.every(key => Object.hasOwn(value, key));
}
function absolute(value: unknown): value is string {
  return typeof value === "string" && value.length > 0 && value.length <= 4096
    && isAbsolute(value) && normalize(value) === value && !/[\u0000-\u001f\u007f]/.test(value);
}
export function bunShimTarget(header: string): string | undefined {
  const shim = /^#!\/bin\/sh\n# omo-ai bun launcher shim v1 - generated by omo-ai; safe to delete, the next launch recreates it\n# entry: ([^\n]+)\nif \[ "\$OMO_RUNTIME" != "node" \] && \[ -x '([^'\n]+)' \]; then exec '([^'\n]+)' '([^'\n]+)' "\$@"; fi\nexec '([^'\n]+)' "\$@"\n?$/.exec(header);
  return shim && shim[1] === shim[4] && shim[4] === shim[5]
    && shim[2] === shim[3] && absolute(shim[2]) && absolute(shim[4])
    && shim[4].endsWith("/install/global/node_modules/omo-ai/bin/omo.js") ? shim[4] : undefined;
}
function pin(value: unknown): value is Pin {
  return record(value) && exact(value, ["path", "sha256", "mode"]) && absolute(value["path"])
    && typeof value["sha256"] === "string" && /^[a-f0-9]{64}$/.test(value["sha256"])
    && typeof value["mode"] === "number" && Number.isInteger(value["mode"])
    && value["mode"] >= 0 && value["mode"] <= 0o7777 && (value["mode"] & 0o022) === 0;
}
function alias(value: unknown): value is Alias {
  return record(value) && exact(value, ["path", "target"]) && absolute(value["path"]) && absolute(value["target"]);
}
function parse(input: string): State {
  const value: unknown = JSON.parse(input);
  if (!record(value) || !exact(value, ["version", "generation", "pins", "aliases"]) || value["version"] !== 2
    || typeof value["generation"] !== "number" || !Number.isSafeInteger(value["generation"]) || value["generation"] < 0
    || !Array.isArray(value["pins"]) || value["pins"].length > 1024 || !value["pins"].every(pin)
    || !Array.isArray(value["aliases"]) || value["aliases"].length > 1024 || !value["aliases"].every(alias)
    || new Set(value["pins"].map(row => row.path)).size !== value["pins"].length
    || new Set(value["aliases"].map(row => row.path)).size !== value["aliases"].length)
    throw new CatalogSourceError("unsafe_source");
  return { version: 2, generation: value["generation"], pins: value["pins"], aliases: value["aliases"] };
}
function same(a: BigIntStats, b: BigIntStats): boolean {
  return a.dev === b.dev && a.ino === b.ino && a.size === b.size && a.mode === b.mode
    && a.mtimeNs === b.mtimeNs && a.ctimeNs === b.ctimeNs;
}
function missing(error: unknown): boolean {
  return error instanceof Error && "code" in error && error.code === "ENOENT";
}
async function safeParents(path: string): Promise<void> {
  const uid = BigInt(process.getuid?.() ?? -1);
  for (let p = await realpath(dirname(path));; p = dirname(p)) {
    const info = await lstat(p, { bigint: true });
    // Root-owned sticky temporary directories do not grant ownership of children.
    const sharedTemporary = info.uid === 0n && (info.mode & 0o1000n) !== 0n;
    if (!info.isDirectory() || (info.uid !== uid && info.uid !== 0n)
      || ((info.mode & 0o022n) !== 0n && !sharedTemporary)) throw new CatalogSourceError("unsafe_source");
    if (p === dirname(p)) break;
  }
}
async function captured(path: string, check: () => void, body = false, privateFile = false, versionSource: "claude" | "cursor" | null = null): Promise<Pin & {
  readonly body: string; readonly header: string; readonly size: number; readonly sourceVersion: string | null;
}> {
  check();
  if (!absolute(path) || await realpath(path) !== path) throw new CatalogSourceError("unsafe_source");
  await safeParents(path);
  const named = await lstat(path, { bigint: true }), uid = BigInt(process.getuid?.() ?? -1);
  if (!named.isFile() || named.nlink !== 1n || (named.uid !== uid && named.uid !== 0n)
    || (privateFile && (named.uid !== uid || (named.mode & 0o777n) !== 0o600n))
    || (named.mode & 0o022n) !== 0n || named.size > BigInt(body ? 262144 : 512 * 1024 * 1024))
    throw new CatalogSourceError("unsafe_source");
  check();
  const handle = await open(path, constants.O_RDONLY | constants.O_NOFOLLOW | constants.O_NONBLOCK);
  try {
    const before = await handle.stat({ bigint: true });
    if (!same(named, before)) throw new CatalogSourceError("stale_source");
    const digest = createHash("sha256"), buffer = Buffer.alloc(65536), chunks: Buffer[] = [];
    let header = "", tail = "";
    const versions = new Set<string>();
    // Read build constants from the same descriptor/hash snapshot, never execute
    // the payload. The bounded overlap covers metadata crossing a read boundary.
    let pattern = versionSource === "claude"
      ? /PACKAGE_URL:"@anthropic-ai\/claude-code",README_URL:"https:\/\/code\.claude\.com\/docs\/en\/overview",VERSION:"([0-9]{1,10}\.[0-9]{1,10}\.[0-9]{1,10}(?:-[A-Za-z0-9.-]{1,64})?)",FEEDBACK_CHANNEL:"https:\/\/github\.com\/anthropics\/claude-code\/issues",BUILD_TIME:"[0-9TZ:.-]{1,40}",GIT_SHA:"[a-f0-9]{40}"/g
      : versionSource === "cursor"
        ? /"\.\/src\/utils\/version\.ts":\([A-Za-z_$][\w$]*,[A-Za-z_$][\w$]*,[A-Za-z_$][\w$]*\)=>\{"use strict";function [A-Za-z_$][\w$]*\(\)\{return null!=="([0-9]{4}\.[0-9]{2}\.[0-9]{2}-[a-f0-9]{7,40})"\?"\1":"unknown"\}/g
        : null;
    for (let offset = 0; offset < Number(before.size);) {
      check();
      const { bytesRead } = await handle.read(buffer, 0, Math.min(buffer.length, Number(before.size) - offset), offset);
      if (bytesRead === 0) throw new CatalogSourceError("stale_source");
      if (offset === 0) {
        header = buffer.subarray(0, Math.min(bytesRead, 4096)).toString("utf8");
        if (versionSource === "claude" && !["cffaedfe", "cefaedfe", "7f454c46"].includes(buffer.subarray(0, 4).toString("hex")))
          pattern = null;
      }
      digest.update(buffer.subarray(0, bytesRead));
      if (pattern) {
        const text = tail + buffer.subarray(0, bytesRead).toString("latin1");
        for (const match of text.matchAll(pattern)) {
          if (match[1]) versions.add(match[1]);
          if (versions.size > 1) throw new CatalogSourceError("identity_mismatch");
        }
        tail = text.slice(-1024);
      }
      if (body) chunks.push(Buffer.from(buffer.subarray(0, bytesRead)));
      offset += bytesRead;
    }
    check();
    if (!same(before, await handle.stat({ bigint: true })) || !same(before, await lstat(path, { bigint: true }))
      || await realpath(path) !== path) throw new CatalogSourceError("stale_source");
    check();
    return { path, sha256: digest.digest("hex"), mode: Number(before.mode & 0o7777n), size: Number(before.size),
      body: body ? Buffer.concat(chunks).toString("utf8") : "", header, sourceVersion: [...versions][0] ?? null };
  } finally { await handle.close(); }
}
async function privateRoot(root: string): Promise<BigIntStats> {
  const info = await lstat(root, { bigint: true });
  if (!info.isDirectory() || info.uid !== BigInt(process.getuid?.() ?? -1)
    || (info.mode & 0o777n) !== 0o700n || await realpath(root) !== root) throw new CatalogSourceError("unsafe_source");
  await safeParents(join(root, "auto-sources.json"));
  return info;
}

/** No import, probe, shell evaluation, credentials, sessions or native authority.
 * Persistent pins/aliases are a first observation, not an automatic rebaseline.
 */
export function createCatalogSourceOwner(directory: string, environment: CatalogSourceEnvironment,
  clock: () => number = performance.now.bind(performance), privateMutationRoots: readonly string[] = []): CatalogSourceOwner {
  const root = catalogRegistryDirectory(directory), statePath = join(root, "auto-sources.json");
  const lifetime = new AbortController();
  let active: Promise<CatalogSourceSnapshot> | undefined;
  async function scan(signal?: AbortSignal): Promise<CatalogSourceSnapshot> {
    const startedAt = Date.now(), deadline = clock() + 4000;
    const check = () => {
      if (lifetime.signal.aborted || signal?.aborted || clock() >= deadline) throw new CatalogSourceError("incomplete");
    };
    const candidates: CatalogSourceCandidate[] = [], sockets: string[] = [];
    const references: { path: string; familyHint: Family | null; classified: boolean }[] = [];
    const failures: { sourceId: string; sourcePath: string; code: FailureCode; relatedPaths?: readonly string[] }[] = [];
    let incomplete = false, scanComplete = false, previous: State = { version: 2, generation: 0, pins: [], aliases: [] };
    let rootIdentity: BigIntStats | undefined;
    const pins = new Map<string, Pin>(), aliases = new Map<string, Alias>(), seen = new Set<string>();
    const visited = new Set<string>();
    const reject = (path: string, code: FailureCode, relatedPaths?: readonly string[]) => failures.push({
      sourceId: `source:${hash(path)}`, sourcePath: path, code, ...(relatedPaths ? { relatedPaths } : {}) });
    async function publish(generation: number, completed: boolean) {
      const identity = rootIdentity;
      if (!identity) throw new CatalogSourceError("unsafe_source");
      // An accepted first observation is flushed even when its final I/O crosses
      // the deadline. The scan must then return incomplete, never repin at restart.
      const publicationCheck = completed ? check : () => {
        if (!rootIdentity) throw new CatalogSourceError("unsafe_source");
      };
      publicationCheck();
      const state: State = { version: 2, generation, pins: [...pins.values()], aliases: [...aliases.values()] };
      const serialized = JSON.stringify(state);
      if (Buffer.byteLength(serialized) > 262144) throw new CatalogSourceError("incomplete");
      const temporary = join(root, `.${randomUUID()}.tmp`);
      const handle = await open(temporary, constants.O_WRONLY | constants.O_CREAT | constants.O_EXCL | constants.O_NOFOLLOW, 0o600);
      let published = false;
      try {
        await handle.writeFile(serialized);
        await handle.sync();
        publicationCheck();
        const currentRoot = await privateRoot(root);
        if (identity.dev !== currentRoot.dev || identity.ino !== currentRoot.ino) throw new CatalogSourceError("unsafe_source");
        try { await captured(statePath, publicationCheck, true, true); }
        catch (error) { if (!missing(error)) throw error; }
        await rename(temporary, statePath);
        published = true;
        const parent = await open(root, constants.O_RDONLY | constants.O_NOFOLLOW);
        try { await parent.sync(); } finally { await parent.close(); }
        publicationCheck();
      } finally {
        await handle.close();
        if (!published) await unlink(temporary);
      }
    }
    async function names(path: string): Promise<readonly string[]> {
      check();
      if (!absolute(path)) return [];
      let directoryHandle;
      try {
        const canonical = await realpath(path);
        // Enumeration is not admission. Unrelated PATH directories may be
        // shared; each executable/manifest still validates its own parents.
        if (visited.size >= 256 && !visited.has(canonical)) throw new CatalogSourceError("incomplete");
        visited.add(canonical);
        directoryHandle = await opendir(canonical);
      } catch (error) { if (missing(error)) return []; throw error; }
      const found: string[] = [];
      try {
        for (;;) {
          check();
          const entry = await directoryHandle.read();
          if (!entry) break;
          if (found.length >= 4096) throw new CatalogSourceError("incomplete");
          found.push(entry.name);
        }
      } finally { await directoryHandle.close(); }
      return found.sort();
    }
    async function observe(path: string, body = false, versionSource: "claude" | "cursor" | null = null) {
      const value = await captured(path, check, body, false, versionSource), old = pins.get(path);
      if (old && (old.sha256 !== value.sha256 || old.mode !== value.mode)) throw new CatalogSourceError("stale_source");
      if (!old) {
        if (pins.size >= 1024) throw new CatalogSourceError("incomplete");
        pins.set(path, { path, sha256: value.sha256, mode: value.mode });
        await publish(previous.generation, false);
        check();
      }
      return value;
    }
    async function resolveAlias(path: string): Promise<string> {
      check();
      await safeParents(path);
      const target = await realpath(path), old = aliases.get(path);
      if (old && old.target !== target) {
        const suffix = "/install/global/node_modules/omo-ai/bin/omo.js";
        const prefix = old.target.endsWith(suffix) ? old.target.slice(0, -suffix.length) : null;
        const original = pins.get(old.target);
        // The original launcher replaces its two Bun symlinks with this exact
        // dual-branch shim. Admit only a new shim to the unchanged pinned entry,
        // never a retargeted link, replaced executable or changed pinned file.
        if (!prefix || target !== path || pins.has(path) || !original
          || ![join(prefix, "bin/omo"), join(prefix, "install/global/node_modules/.bin/omo")].includes(path))
          throw new CatalogSourceError("stale_source");
        const entry = await captured(old.target, check), shim = await captured(path, check);
        if (entry.sha256 !== original.sha256 || entry.mode !== original.mode || shim.size > 4096
          || (shim.mode & 0o111) === 0 || bunShimTarget(shim.header) !== old.target)
          throw new CatalogSourceError("stale_source");
        if (pins.size >= 1024) throw new CatalogSourceError("incomplete");
        pins.set(path, { path, sha256: shim.sha256, mode: shim.mode });
        aliases.set(path, { path, target });
        await publish(previous.generation, false);
      }
      if (!old) {
        if (aliases.size >= 1024) throw new CatalogSourceError("incomplete");
        aliases.set(path, { path, target });
        await publish(previous.generation, false);
      }
      check();
      return target;
    }
    async function executable(path: string, hint: Family | null) {
      // Qualified product readers own these exact mutation namespaces, including
      // before/after observation. Automatic first-observation pins must not also
      // bind aliases which that authorized update is expected to replace.
      if (privateMutationRoots.some(root => path === root || path.startsWith(`${root}/`))) return;
      if (seen.has(path)) return;
      seen.add(path);
      const used: Pin[] = [], edges: Alias[] = [];
      const relatedPaths = new Set<string>([path]);
      const resolved = async (p: string) => {
        const old = aliases.get(p);
        if (old) { relatedPaths.add(p); relatedPaths.add(old.target); }
        const target = await resolveAlias(p);
        relatedPaths.add(p); relatedPaths.add(target);
        edges.push({ path: p, target });
        return target;
      };
      const take = async (p: string, body = false, versionSource: "claude" | "cursor" | null = null) => {
        const canonical = await resolved(p), value = await observe(canonical, body, versionSource);
        used.push({ path: canonical, sha256: value.sha256, mode: value.mode });
        return value;
      };
      const bound = async (parent: string, bin: unknown, physical: string) => {
        const entries = typeof bin === "string" ? [bin] : record(bin) ? Object.values(bin) : [];
        for (const entry of entries) {
          if (typeof entry !== "string" || isAbsolute(entry) || entry.split("/").includes("..")) continue;
          const p = resolve(parent, entry);
          let target: string;
          try { target = await realpath(p); } catch (error) { if (missing(error)) continue; throw error; }
          if (target !== physical || !target.startsWith(`${parent}/`)) continue;
          if (await resolved(p) !== physical) throw new CatalogSourceError("stale_source");
          return true;
        }
        return false;
      };
      const disprove = async (physical: string, expected: Family) => {
        for (let parent = dirname(physical), depth = 0; depth < 16; depth++, parent = dirname(parent)) {
          let ref;
          try { ref = await take(join(parent, "package.json"), true); }
          catch (error) {
            if (!missing(error)) throw error;
            if (parent === dirname(parent)) break;
            continue;
          }
          const metadata: unknown = JSON.parse(ref.body);
          if (!record(metadata)) continue;
          if (!await bound(parent, metadata["bin"], physical)) continue;
          const actual = Object.entries(packages).find(([name]) => name === metadata["name"])?.[1];
          if (actual && actual !== expected) throw new CatalogSourceError("identity_mismatch");
        }
      };
      try {
        try { await lstat(path); } catch (error) { if (missing(error)) return; throw error; }
        references.push({ path, familyHint: hint, classified: false });
        let physical = await resolved(path);
        const chain = new Set<string>();
        let primary = physical, file;
        for (;;) {
          if (chain.size >= 16 || chain.has(physical)) throw new CatalogSourceError("stale_source");
          chain.add(physical);
          const claudeLayout = join(environment.home, ".local/share/claude/versions");
          if (dirname(physical) === claudeLayout) {
            // Bind the vendor's original alias, including when this scan arrived
            // through a renamed PATH alias or a versions-directory enumeration.
            const original = join(environment.home, ".local/bin/claude");
            if (await realpath(original) !== physical) return;
            if (await resolved(original) !== physical) throw new CatalogSourceError("stale_source");
          }
          file = await take(physical, false, dirname(physical) === claudeLayout ? "claude" : null);
          if ((file.mode & 0o111) === 0) throw new CatalogSourceError("unsafe_source");
          if (!/^#!\/(?:bin\/(?:ba)?sh|usr\/bin\/env (?:ba)?sh)\r?\n/.test(file.header)) break;
          const isolatedOmo = /^#!\/bin\/sh\nexport BUN_INSTALL="([^"$`\\\n]+)"\nexec "([^"$`\\\n]+)" "\$@"\n?$/.exec(file.header);
          const isolatedTarget = isolatedOmo && absolute(isolatedOmo[1] ?? "")
            && isolatedOmo[2] === join(isolatedOmo[1] ?? "", "install/global/node_modules/omo-ai/bin/omo.js")
            ? isolatedOmo[2] : undefined;
          const bunTarget = bunShimTarget(file.header);
          const target = /^#!\/bin\/sh\nexec "([^"$`\\\n]+)" "\$@"\n?$/.exec(file.header)?.[1] ?? isolatedTarget ?? bunTarget;
          if (!target || file.size > 4096 || !absolute(target)) {
            // The reviewed Cursor launcher is not an arbitrary shell resolver.
            if (file.sha256 !== "8756ac4a808cc90b220416ac8743560aa473a94d6fe5911bb602c250c046c4a3") return;
            await take(join(dirname(physical), "node"));
            const payload = await take(join(dirname(physical), "index.js"), false, "cursor");
            await disprove(payload.path, "cursor");
            const manifest = await take(join(dirname(physical), "package.json"), true);
            const metadata: unknown = JSON.parse(manifest.body);
            if (!record(metadata) || metadata["name"] !== "@anysphere/agent-cli-runtime") return;
            const primaryPin = used.find(p => p.path === primary);
            if (!primaryPin) throw new CatalogSourceError("stale_source");
            const resources = [primaryPin, manifest, payload];
            add("cursor", primary, used, edges, resources, payload.sourceVersion);
            return;
          }
          primary = physical = await resolved(target);
        }
        let family: Family | null = null, version: string | null = null, manifestPin: Pin | undefined;
        let managedEngine: CatalogSourceCandidate["managedEngine"], engineResources: readonly Pin[] = [];
        for (let parent = dirname(physical), depth = 0; depth < 16; depth++, parent = dirname(parent)) {
          const p = join(parent, "package.json");
          let manifest;
          try { manifest = await take(p, true); }
          catch (error) { if (missing(error)) { if (parent === dirname(parent)) break; continue; } throw error; }
          const value: unknown = JSON.parse(manifest.body);
          if (!record(value)) continue;
          if (!await bound(parent, value["bin"], physical)) continue;
          const mapped = Object.entries(packages).find(([name]) => name === value["name"])?.[1];
          if (!mapped) return;
          if (family && family !== mapped) throw new CatalogSourceError("identity_mismatch");
          family = mapped;
          manifestPin = manifest;
          if (typeof value["version"] === "string" && value["version"].length <= 4096
            && value["version"].length > 0 && !/[\u0000-\u001f\u007f]/.test(value["version"])) version = value["version"];
          if (mapped === "omo" && record(value["dependencies"]) && typeof value["dependencies"]["@code-yeongyu/senpi"] === "string") {
            if (!record(value["bin"]) || typeof value["bin"]["omo"] !== "string"
              || !await bound(parent, { omo: value["bin"]["omo"] }, physical)
              || physical !== join(parent, "bin/omo.js")) return;
            let engineRoot: string | undefined, engineManifest: Pin | undefined;
            let engineMetadata: Record<string, unknown> | undefined;
            for (let ancestor = parent, level = 0; level < 16; level++, ancestor = dirname(ancestor)) {
              const enginePath = join(ancestor, "node_modules/@code-yeongyu/senpi/package.json");
              try {
                const engine = await take(enginePath, true), metadata: unknown = JSON.parse(engine.body);
                if (!record(metadata) || metadata["name"] !== "@code-yeongyu/senpi"
                  || metadata["version"] !== value["dependencies"]["@code-yeongyu/senpi"]
                  || metadata["main"] !== "./dist/index.js" || !record(metadata["exports"])
                  || !record(metadata["exports"]["."]) || metadata["exports"]["."]["import"] !== "./dist/index.js") return;
                engineRoot = dirname(engine.path);
                engineManifest = engine;
                engineMetadata = metadata;
                break;
              } catch (error) { if (!missing(error)) throw error; }
              if (ancestor === dirname(ancestor)) break;
            }
            if (!engineRoot || !engineManifest || !engineMetadata) return;
            const index = await take(join(engineRoot, "dist/index.js"));
            if (index.path !== join(engineRoot, "dist/index.js")) throw new CatalogSourceError("identity_mismatch");
            let entry = join(engineRoot, "dist/bundle/cli.js");
            try { await lstat(entry); } catch (error) {
              if (!missing(error)) throw error;
              entry = join(engineRoot, "dist/cli.js");
            }
            const engineEntry = await resolved(entry);
            if (!engineEntry.startsWith(`${engineRoot}/`)) throw new CatalogSourceError("identity_mismatch");
            const enginePin = await take(engineEntry);
            if ((enginePin.mode & 0o111) === 0 || !record(engineMetadata["bin"])
              || typeof engineMetadata["bin"]["pi"] !== "string" || typeof engineMetadata["bin"]["senpi"] !== "string")
              throw new CatalogSourceError("identity_mismatch");
            // Older engines (<= 2026.9.x) declare `pi` at dist/bundle/cli.js but ship only
            // dist/cli.js: a known pre-bundle layout, not a tampered install. Leave it
            // unclassified so it is listed as removable without quarantining the scan.
            if (!await bound(engineRoot, { pi: engineMetadata["bin"]["pi"] }, engineEntry)
              || !await bound(engineRoot, { senpi: engineMetadata["bin"]["senpi"] }, engineEntry)) {
              const declared = engineMetadata["bin"]["pi"];
              let declaredMissing = false;
              try { await lstat(resolve(engineRoot, declared)); } catch (error) { if (missing(error)) declaredMissing = true; else throw error; }
              if (declaredMissing && engineEntry === join(engineRoot, "dist/cli.js")) return;
              throw new CatalogSourceError("identity_mismatch");
            }
            await disprove(engineEntry, "pi");
            const brand = await take(join(engineRoot, "dist/core/brand.js"));
            if (!brand.path.startsWith(`${engineRoot}/`)) throw new CatalogSourceError("identity_mismatch");
            // Collect the physical engine relation before helper verification.
            // A changed helper must quarantine this engine's Pi aliases too,
            // without excluding unrelated OmO/Pi installations.
            const wrapperBin = join(parent, "bin"), pending = [wrapperBin];
            // Missing old helpers remain a changed baseline, not an opportunity
            // to learn a smaller source inventory after an external write.
            for (const reference of previous.pins.filter(pin => pin.path.startsWith(`${wrapperBin}/`))) {
              try { await take(reference.path); }
              catch (error) {
                if (missing(error)) throw new CatalogSourceError("stale_source");
                throw error;
              }
            }
            while (pending.length) {
              const directory = pending.pop();
              if (directory === undefined) throw new CatalogSourceError("incomplete");
              if (await realpath(directory) !== directory) throw new CatalogSourceError("identity_mismatch");
              for (const name of await names(directory)) {
                const path = join(directory, name), info = await lstat(path);
                if (info.isDirectory()) pending.push(path);
                else {
                  const dependency = await take(path);
                  if (!info.isFile() || dependency.path !== path) throw new CatalogSourceError("identity_mismatch");
                }
              }
            }
            engineResources = [engineManifest, enginePin];
            managedEngine = { family: "pi", installationId: `install:${hash(engineEntry)}`,
              executableRealpath: engineEntry, installedVersion: value["dependencies"]["@code-yeongyu/senpi"] };
          }
          if (mapped === "claude" && file.sha256 === "61ad63033d9c8155d5e60a29f45dc4665afa07631c0b108e62cc83bf45ba490e") {
            if (process.platform !== "darwin" || process.arch !== "arm64") return;
            let platformRoot: string | undefined;
            for (let ancestor = parent, level = 0; level < 16; level++, ancestor = dirname(ancestor)) {
              const p = join(ancestor, "node_modules/@anthropic-ai/claude-code-darwin-arm64/package.json");
              try {
                const ref = await take(p, true), metadata: unknown = JSON.parse(ref.body);
                if (!record(metadata) || metadata["name"] !== "@anthropic-ai/claude-code-darwin-arm64") return;
                platformRoot = dirname(ref.path);
                break;
              } catch (error) { if (!missing(error)) throw error; }
              if (ancestor === dirname(ancestor)) break;
            }
            if (!platformRoot) return;
            const leaf = join(platformRoot, "claude"), target = await resolved(leaf), dependency = await take(target);
            if (!target.startsWith(`${platformRoot}/`) || (dependency.mode & 0o111) === 0)
              throw new CatalogSourceError("identity_mismatch");
            await disprove(target, "claude");
          }
          if (mapped === "grok" && file.sha256 === "378a68c4ec3b95272a8f12f7548548067eb6959a63151a299389dc9a72817f2e") {
            // Missing canonical binary would make this bootstrap write/decompress.
            // Read-only discovery deliberately does not follow that branch.
            const leaf = join(environment.home, ".grok/bin/grok"), target = await resolved(leaf);
            const dependency = await take(target);
            if ((dependency.mode & 0o111) === 0) throw new CatalogSourceError("unsafe_source");
            await disprove(target, "grok");
          }
          // Resolve the exact reviewed npm Codex native dependency without import.
          if (mapped === "codex" && file.sha256 === "61b0194f3bb6534439c8d26a3ed57d0805f84b884588b761795323eeb92fcf70") {
            const triple = process.platform === "darwin" && process.arch === "arm64" ? "aarch64-apple-darwin" : null;
            if (!triple) return;
            let native: string | undefined, nativeRoot = parent;
            for (let ancestor = parent, level = 0; level < 16; level++, ancestor = dirname(ancestor)) {
              const optional = join(ancestor, "node_modules", "@openai", "codex-darwin-arm64", "package.json");
              try {
                const platformManifest = await take(optional, true);
                const platformValue: unknown = JSON.parse(platformManifest.body);
                if (!record(platformValue) || platformValue["name"] !== "@openai/codex"
                  || platformValue["version"] !== `${version}-darwin-arm64`) return;
                native = join(dirname(platformManifest.path), "vendor", triple, "bin", "codex");
                nativeRoot = dirname(platformManifest.path);
                break;
              } catch (error) { if (!missing(error)) throw error; }
              if (ancestor === dirname(ancestor)) break;
            }
            native ??= join(parent, "vendor", triple, "bin", "codex");
            const target = await resolved(native), nativePin = await take(target);
            if (!target.startsWith(`${nativeRoot}/`)) throw new CatalogSourceError("identity_mismatch");
            if ((nativePin.mode & 0o111) === 0) throw new CatalogSourceError("unsafe_source");
            await disprove(target, "codex");
          }
        }
        if (file.sourceVersion !== null && family !== null && family !== "claude")
          throw new CatalogSourceError("identity_mismatch");
        if (!family) {
          // Native layout narrows the source; only its embedded vendor build
          // metadata supplies identity/version, never the directory's version.
          if (file.sourceVersion !== null) {
            await disprove(physical, "claude");
            family = "claude"; version = file.sourceVersion;
          } else if (file.sha256 === "5086b9b64d8bb842e1f599cdd3767ab08c6b2266e462fcc5686ae4b019cca8f7") {
            await disprove(physical, "claude");
            family = "claude"; version = "2.1.247";
          } else if (file.sha256 === "d15693410c904242c1c3423a579f60a81e018444bb51fbccc6505f988b62a91d") {
            await disprove(physical, "agy");
            family = "agy"; version = null;
          }
        }
        if (!family) return;
        const primaryPin = used.find(p => p.path === primary);
        if (!primaryPin) throw new CatalogSourceError("stale_source");
        // Grok's native version needs its separate vendor receipt, not wrapper metadata.
        add(family, primary, used, edges, manifestPin ? [primaryPin, manifestPin, ...engineResources] : [primaryPin],
          family === "grok" ? null : version);
        if (managedEngine) {
          const index = candidates.findIndex(row => row.family === family && row.installation.executableRealpath === primary);
          const candidate = candidates[index];
          if (!candidate) throw new CatalogSourceError("stale_source");
          candidates[index] = { ...candidate, managedEngine };
        }
      } catch (error) {
        if (missing(error)) return;
        if (error instanceof CatalogSourceError && error.code === "incomplete") throw error;
        reject(path, error instanceof CatalogSourceError && error.code === "identity_mismatch" ? "identity_mismatch" : "verification_failed",
          [...relatedPaths]);
      }
    }
    function add(family: Family, primary: string, used: readonly Pin[], edges: readonly Alias[], visible: readonly Pin[], version: string | null) {
      for (const row of references) if (edges.some(edge => edge.path === row.path)) row.classified = true;
      const index = candidates.findIndex(row => row.family === family && row.installation.executableRealpath === primary);
      const existing = candidates[index];
      if (existing) {
        const merged = new Map(existing.pins.map(p => [p.path, p]));
        for (const p of used) {
          const old = merged.get(p.path);
          if (old && (old.sha256 !== p.sha256 || old.mode !== p.mode)) throw new CatalogSourceError("stale_source");
          merged.set(p.path, p);
        }
        candidates[index] = { ...existing, pins: [...merged.values()], aliases: [...existing.aliases, ...edges]
          .filter((row, i, all) => all.findIndex(other => other.path === row.path) === i) };
        return;
      }
      if (candidates.length >= 64) throw new CatalogSourceError("incomplete");
      const resources = visible.map(p => ({ resourceId: `resource:${hash(p.path)}`, realpath: p.path,
        fingerprint: `sha256:${p.sha256}` })).sort((a, b) => a.realpath.localeCompare(b.realpath));
      candidates.push({ candidateId: `source:${hash(JSON.stringify([family, primary]))}`, family, pins: used, aliases: edges,
        installation: { installationId: `install:${hash(primary)}`, family, channel: "unknown",
          executableRealpath: primary, owner: { kind: "unknown", reason: "unverified_owner" },
          installedVersion: version === null ? { kind: "unknown", reason: "not_captured" } : { kind: "known", version },
          resources, resourcesFingerprint: `sha256:${hash(JSON.stringify(resources))}` } });
    }
    async function socket(path: string) {
      check();
      try {
        await safeParents(path);
        const before = await lstat(path, { bigint: true });
        if (!before.isSocket() || before.uid !== BigInt(process.getuid?.() ?? -1)
          || (before.mode & 0o777n) !== 0o600n || await realpath(dirname(path)) !== dirname(path)
          || !same(before, await lstat(path, { bigint: true }))) throw new CatalogSourceError("unsafe_source");
        if (sockets.length >= 32) throw new CatalogSourceError("incomplete");
        if (!sockets.includes(path)) sockets.push(path);
      } catch (error) {
        if (missing(error)) return;
        if (error instanceof CatalogSourceError && error.code === "incomplete") throw error;
        reject(path, "verification_failed");
      }
    }
    try {
      check();
      if (!absolute(environment.home) || environment.prefixes.some(p => !absolute(p))) throw new CatalogSourceError("unsafe_source");
      await mkdir(root, { mode: 0o700 }).catch(error => {
        if (!(error instanceof Error && "code" in error && error.code === "EEXIST")) throw error;
      });
      rootIdentity = await privateRoot(root);
      try { previous = parse((await captured(statePath, check, true, true)).body); }
      catch (error) { if (!missing(error)) throw error; }
      for (const row of previous.pins) pins.set(row.path, row);
      for (const row of previous.aliases) aliases.set(row.path, row);
      const bins = new Set(environment.path.split(":").filter(absolute));
      for (const suffix of [".local/bin", ".bun/bin", ".grok/bin"]) bins.add(join(environment.home, suffix));
      for (const prefix of environment.prefixes) bins.add(join(prefix, "bin"));
      const prefixes = new Set(environment.prefixes);
      for (const bin of bins) if (basename(bin) === "bin") prefixes.add(dirname(bin));
      const nvm = join(environment.home, ".nvm/versions/node");
      for (const name of await names(nvm)) { prefixes.add(join(nvm, name)); bins.add(join(nvm, name, "bin")); }
      for (const bin of bins) {
        const entries = await names(bin);
        for (const [name, hint] of Object.entries(commands)) if (entries.includes(name)) await executable(join(bin, name), hint);
        for (const name of entries) {
          check();
          const p = join(bin, name);
          if (privateMutationRoots.some(root => p === root || p.startsWith(`${root}/`))) continue;
          if (seen.has(p)) continue;
          const info = await lstat(p);
          if (info.isSymbolicLink()) {
            try {
              const target = await realpath(p);
              if (candidates.some(row => row.pins.some(pin => pin.path === target && (pin.mode & 0o111) !== 0)))
                await executable(p, null);
            }
            catch (error) {
              // This loop admits only aliases to previously known candidates.
              if (!(error instanceof Error && "code" in error && ["ENOENT", "EACCES", "EPERM"].includes(String(error.code))))
                reject(p, "verification_failed");
            }
          }
        }
      }
      const moduleRoots = [join(environment.home, ".bun/install/global/node_modules")];
      for (const prefix of prefixes) {
        moduleRoots.push(join(prefix, "lib/node_modules"), join(prefix, "node_modules"));
        for (const layout of ["opt", "Cellar", "Caskroom"]) {
          for (const name of await names(join(prefix, layout))) {
            if (!(name in commands) && !Object.keys(packages).some(pkg => pkg.split("/").at(-1) === name)) continue;
            if (!["claude-code", "codex", "grok", "omo-ai", "omp", "cursor-agent", "agy"].includes(name)) continue;
            const installed = join(prefix, layout, name);
            const versions = layout === "opt" ? [""] : await names(installed);
            for (const version of versions) {
              if (version.startsWith(".")) continue;
              const bin = join(installed, version, "bin");
              for (const command of Object.keys(commands)) {
                await executable(join(bin, command), null);
                await executable(join(installed, version, command), null);
              }
              try { await observe(await realpath(join(installed, version, "INSTALL_RECEIPT.json")), true); }
              catch (error) {
                if (!missing(error)) throw error;
              }
              moduleRoots.push(join(installed, version, "lib/node_modules"));
            }
          }
        }
      }
      for (const modules of moduleRoots) for (const [name, hint] of Object.entries(packages)) {
        const manifestPath = join(modules, name, "package.json");
        if (privateMutationRoots.some(root => manifestPath === root || manifestPath.startsWith(`${root}/`))) continue;
        try {
          const manifest = await observe(await resolveAlias(manifestPath), true), metadata: unknown = JSON.parse(manifest.body);
          if (!record(metadata) || metadata["name"] !== name) continue;
          const bin = metadata["bin"], entries = typeof bin === "string" ? [bin] : record(bin) ? Object.values(bin) : [];
          for (const entry of entries) if (typeof entry === "string" && !isAbsolute(entry)
            && !entry.split("/").includes("..")) await executable(resolve(dirname(manifest.path), entry), hint);
        } catch (error) {
          if (missing(error)) continue;
          if (error instanceof CatalogSourceError && error.code === "incomplete") throw error;
          references.push({ path: manifestPath, familyHint: hint, classified: false });
          reject(manifestPath, "verification_failed");
        }
      }
      for (const [suffix, leaf, hint] of [
        [".local/share/claude/versions", "", "claude"], [".local/share/cursor-agent/versions", "cursor-agent", "cursor"],
        [".grok/downloads", "", "grok"],
      ] as const) for (const version of await names(join(environment.home, suffix))) {
        if (hint === "grok" && !/^grok-[A-Za-z0-9._-]+$/.test(version)) continue;
        await executable(join(environment.home, suffix, version, leaf), hint);
      }
      const config = environment.configHome ?? join(environment.home, ".config");
      if (!absolute(config)) throw new CatalogSourceError("unsafe_source");
      for (const app of ["herdr", "herdr-dev"]) {
        const base = join(config, app);
        await socket(join(base, "herdr.sock"));
        for (const name of await names(join(base, "sessions"))) {
          if (name === "default" || name === "." || name === ".." || !/^[A-Za-z0-9._-]{1,64}$/.test(name)) continue;
          check();
          const session = join(base, "sessions", name);
          if ((await lstat(session)).isDirectory()) await socket(join(session, "herdr.sock"));
        }
      }
      if (environment.socket && absolute(environment.socket)) await socket(environment.socket);
      // Group only an exactly proven physical engine after all aliases and
      // independent prefixes have been collected. Never grant wrapper ownership.
      for (const wrapper of [...candidates]) {
        const engine = wrapper.managedEngine;
        if (!engine) continue;
        if (candidates.some(row => row !== wrapper
          && row.managedEngine?.executableRealpath === engine.executableRealpath))
          throw new CatalogSourceError("identity_mismatch");
        const physical = candidates.find(row => row.family === "pi"
          && row.installation.executableRealpath === engine.executableRealpath);
        if (!physical) continue;
        add("omo", wrapper.installation.executableRealpath, physical.pins, physical.aliases, [], null);
        candidates.splice(candidates.indexOf(physical), 1);
      }
      check();
      scanComplete = true;
      if (failures.length > 0) throw new CatalogSourceError("incomplete");
      await publish(previous.generation + 1, true);
      check();
    } catch (error) {
      incomplete = true;
      if (!(error instanceof CatalogSourceError && error.code === "incomplete")) reject(statePath, "verification_failed");
    }
    return { generation: previous.generation + (incomplete ? 0 : 1), startedAt, completedAt: Date.now(),
      state: incomplete ? "incomplete" : "complete", candidates, sockets, references, failures,
      scanComplete,
      families: FAMILIES.map(family => {
        const count = candidates.filter(row => row.family === family).length;
        return { family, count, state: incomplete ? "incomplete" : count > 0 ? "observed"
          : references.some(row => !row.classified) ? "unclassified" : "missing" };
      }) };
  }
  return {
    refresh(signal) {
      if (!active) {
        active = scan(signal);
        void active.finally(() => { active = undefined; });
      }
      return active;
    },
    async verify(candidate, signal) {
      const deadline = clock() + 2000;
      const check = () => {
        if (lifetime.signal.aborted || signal?.aborted || clock() >= deadline) throw new CatalogSourceError("incomplete");
      };
      try {
        for (const edge of candidate.aliases) {
          check();
          await safeParents(edge.path);
          if (await realpath(edge.path) !== edge.target) return false;
          check();
        }
        for (const p of candidate.pins) {
          const current = await captured(p.path, check);
          if (current.sha256 !== p.sha256 || current.mode !== p.mode) return false;
        }
        for (const edge of candidate.aliases) {
          check();
          await safeParents(edge.path);
          if (await realpath(edge.path) !== edge.target) return false;
          check();
        }
        check();
        return true;
      } catch { return false; }
    },
    async close() { lifetime.abort(); await active; },
  };
}
